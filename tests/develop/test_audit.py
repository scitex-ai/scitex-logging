import shutil
from pathlib import Path

import pytest


@pytest.mark.skipif(
    shutil.which("scitex-dev") is None,
    reason="scitex-dev not installed — add `scitex-dev[cli-audit]` to [project.optional-dependencies.dev]",
)
# audit-all fans out to 6 sub-auditor subprocesses (audit-cli,
# audit-mcp-tools, audit-skills, audit-python-apis, audit-project,
# audit-django), each re-importing the package fresh; on a loaded
# or NFS-backed host this legitimately runs well past this repo's
# global [tool.pytest.ini_options] `timeout` default even when the
# audit itself is completely clean. Override per-test rather than
# raise the global cap for every other (fast) test.
@pytest.mark.timeout(600)
def test_audit_all_clean():
    # Arrange
    from scitex_dev.testing import audit_all_for_package

    # `path=` PINS the tree under audit to THIS checkout. Without
    # it the auditor falls back to guessing from the cwd, which
    # grades the parent repo when pytest runs from a git worktree
    # and somebody else's tree on a shared runner. A gate that
    # grades the wrong tree is worse than no gate.
    # This file lives at tests/develop/test_audit.py,
    # so parents[2] is the package root — and
    # `test_audit_gate_anchor_resolves_to_package_root` below is what
    # proves that number is the right one.

    # Act
    # `path=` stays a SELF-CONTAINED expression rather than being
    # lifted to a local. Two reasons, and the first is not stylistic:
    # test__install_gate_anchor.py EVALUATES this exact keyword
    # expression with `__file__` bound, so it measures what the
    # emitted code DOES rather than what it says. A bare Name is not
    # evaluable in isolation, which would have downgraded a real
    # behavioural check into a text comparison. Second, a reader of
    # this call sees which tree is graded without tracing a variable.
    result = audit_all_for_package(
        'scitex-logging',
        path=Path(__file__).resolve().parents[2],
    )

    # Assert — audit_all_for_package returns None on a clean
    # audit and raises AssertionError on any unexpected finding,
    # so reaching this point with result is None means clean.
    assert result is None


# A WRONG ANCHOR STILL LOOKS PINNED. `parents[N]` depends on how deep
# this file sits, so a copy generated for a different layout resolves
# confidently to the wrong directory and grades it. This is the
# difference between `pinned` and `pinned CORRECTLY` — without it a
# bulk regeneration could write many plausible-looking wrong anchors
# and nothing would say so.
#
# It is a SEPARATE test, not a second assert inside the one above,
# because STX-TQ007 is an error-severity rule with no suppression:
# when the first assert fails every later one is silently skipped, so
# a two-assert gate reported `audit clean` questions that never ran.
# It also carries no skipif — a wrong anchor is a defect in THIS file
# and stays worth catching on a host with no scitex-dev installed.
def test_audit_gate_anchor_resolves_to_package_root():
    # Arrange
    anchor = Path(__file__).resolve().parents[2]

    # Act
    landed_on_package_root = (anchor / "pyproject.toml").is_file()

    # Assert
    assert landed_on_package_root, (
        f"audit-gate anchor parents[2] resolved to {anchor}, which "
        "has no pyproject.toml — this gate was generated for a "
        "different directory depth and would grade the wrong tree. "
        "Regenerate: scitex-dev ecosystem install-audit-gate scitex-logging"
    )
